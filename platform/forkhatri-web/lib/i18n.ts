const dictionaries: Record<Lang, Dictionary> = { en, hi, te, mr, kn };

/** `short` is the compact chip label on the entrance's language switch. */
export const LANGUAGES: { code: Lang; native: string; short: string }[] = [
  { code: "en", native: "English", short: "EN" },
  { code: "hi", native: "हिन्दी", short: "हि" },
  { code: "te", native: "తెలుగు", short: "తె" },
  { code: "mr", native: "मराठी", short: "म" },
  { code: "kn", native: "ಕನ್ನಡ", short: "ಕ" },
];

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): Translate {
  const dictionary = dictionaries[lang] ?? en;
  return (key, vars) => {
    const template = dictionary[key] ?? en[key];
    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
  };
}

export function langFromNavigator(): Lang {
  if (typeof navigator === "undefined") return "en";
  for (const candidate of navigator.languages ?? [navigator.language]) {
    const base = candidate.toLowerCase().split("-")[0];
    if (isLang(base)) return base;
  }
  return "en";
}

/** Maps a service error code to localized text; `retryAfter` feeds rate_limited. */
export function errorText(t: Translate, code: string, retryAfter: number | null = null): string {
  switch (code) {
    case "rate_limited": {
      if (!retryAfter) return t("err_rate_limited_generic");
      const time = retryAfter >= 90 ? t("minutes", { n: Math.ceil(retryAfter / 60) }) : t("seconds", { n: retryAfter });
      return t("err_rate_limited", { time });
    }
    case "invalid_identifier":
    case "code_invalid":
    case "code_expired":
    case "code_attempts_exhausted":
    case "invalid_credentials":
    case "not_signed_in":
    case "module_unavailable":
    case "module_unknown":
    case "validation_failed":
    case "origin_not_allowed":
    case "delivery_unavailable":
    case "reauth_failed":
    case "reauth_required":
    case "admin_role_held":
    case "no_contact":
    case "network":
      return t(`err_${code}` as MessageKey);
    default:
      return t("err_unknown");
  }
}

export function relativeTime(lang: Lang, iso: string): string {
  const then = Date.parse(iso);
  if (Number.isNaN(then)) return "";
  const diffSeconds = Math.round((then - Date.now()) / 1000);
  const format = new Intl.RelativeTimeFormat(INTL_LOCALE[lang] ?? "en-IN", { numeric: "auto" });
  const units: [Intl.RelativeTimeFormatUnit, number][] = [
    ["year", 31_536_000],
    ["month", 2_592_000],
    ["week", 604_800],
    ["day", 86_400],
    ["hour", 3_600],
    ["minute", 60],
  ];
  for (const [unit, size] of units) {
    if (Math.abs(diffSeconds) >= size) return format.format(Math.round(diffSeconds / size), unit);
  }
  return format.format(0, "minute");
}
