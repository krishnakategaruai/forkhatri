const DICTS: Record<Lang, Dict> = { en, hi, te, mr, kn };

export type AdminT = (key: AdminKey, vars?: Record<string, string | number>) => string;

export function adminTranslator(lang: Lang): AdminT {
  const dict = DICTS[lang] ?? en;
  return (key, vars) => {
    let text = dict[key] ?? en[key] ?? key;
    if (vars) for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
    return text;
  };
}

/** A key that may not exist (role, reason, action from a module): falls back to readable words. */
export function adminLabel(t: AdminT, key: string, fallback?: string): string {
  const value = t(key as AdminKey);
  if (value !== key) return value;
  return fallback ?? humanise(key.split("_").slice(1).join("_") || key);
}

export function humanise(code: string): string {
  const words = code.replace(/[._-]+/g, " ").trim();
  return words ? words[0].toUpperCase() + words.slice(1) : code;
}
