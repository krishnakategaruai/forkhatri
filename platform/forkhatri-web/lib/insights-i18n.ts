const dictionaries: Record<Lang, Dictionary> = { en, hi, te };

export type InsightsT = (key: InsightsKey, vars?: Record<string, string | number>) => string;

export function insightsTranslator(lang: Lang): InsightsT {
  const dictionary = dictionaries[lang] ?? en;
  return (key, vars) => {
    const template = dictionary[key] ?? en[key];
    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
  };
}

/** Enum values from the modules ("female", "never_married", "telugu") → reader's words. */
export function valueLabel(t: InsightsT, value: string): string {
  return value in en ? t(value as InsightsKey) : value.replace(/_/g, " ").replace(/^\w/, (c) => c.toUpperCase());
}
