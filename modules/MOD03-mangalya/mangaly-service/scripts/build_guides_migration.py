"""Write migration 064 (the first guides) from
`app/components/guides/content.json`.

Run after editing the JSON:  python -m scripts.build_guides_migration
The migration inserts each guide and updates one that already exists, so a
fresh database and an existing one end up the same.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "app" / "components" / "guides" / "content.json"
TARGET = ROOT.parent / "07a-db-implementation" / "migrations" / "064-guides-content.sql"
QUOTE = "$guide$"
UPSERT = (
    "INSERT INTO mangaly_content.guide\n"
    "  (slug, category, sort_order, minutes, video_url, action_href, content)\n"
    "VALUES ({values})\n"
    "ON CONFLICT (slug) DO UPDATE SET category = EXCLUDED.category,\n"
    "  sort_order = EXCLUDED.sort_order, minutes = EXCLUDED.minutes,\n"
    "  video_url = EXCLUDED.video_url, action_href = EXCLUDED.action_href,\n"
    "  content = EXCLUDED.content, updated_at = now();\n"
)


def _sql_text(value: str | None) -> str:
    return "NULL" if value is None else "'" + value.replace("'", "''") + "'"


def main() -> None:
    guides = json.loads(SOURCE.read_text(encoding="utf-8"))
    lines = [
        "-- 064 — The first guides (generated by scripts/build_guides_migration.py",
        "-- from mangaly-service/app/components/guides/content.json; edit that file,",
        "-- not this one). Idempotent.",
        "",
    ]
    for order, g in enumerate(guides, start=1):
        body = json.dumps(g["content"], ensure_ascii=False)
        assert QUOTE not in body
        values = ", ".join(
            [
                _sql_text(g["slug"]),
                _sql_text(g["category"]),
                str(order * 10),
                str(int(g["minutes"])),
                _sql_text(g.get("video_url")),
                _sql_text(g.get("action_href")),
                f"{QUOTE}{body}{QUOTE}::jsonb",
            ]
        )
        lines.append(UPSERT.format(values=values))
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {TARGET.name}: {len(guides)} guides")


if __name__ == "__main__":
    main()
